import math
import sys

BODY_MASS = 0.68
ARM_M = 0.17
ROTOR_MASS = 0.009
MAX_THRUST_N = 6.0
MAX_SPIN = 838
REACTION = 0.016


def rotor_block(index, count):
    angle = 2.0 * math.pi * index / count
    x = ARM_M * math.cos(angle)
    y = ARM_M * math.sin(angle)
    clockwise = index % 2 == 0
    mesh = "prop_cw" if clockwise else "prop_ccw"
    colour = "1.0 0.2 0.2 0.6" if index == 0 else "0.2 0.4 1.0 0.6"
    return f"""      <body name="rotor_{index}" pos="{x:.5f} {y:.5f} 0.01">
        <joint name="rotor_{index}_joint" type="hinge" axis="0 0 1"
               damping="0.00005" frictionloss="0.0001"/>
        <inertial pos="0 0 0" mass="{ROTOR_MASS}"
                  diaginertia="7.669e-06 7.507e-06 1.755e-07"/>
        <geom name="prop_{index}" type="mesh" mesh="{mesh}"
              contype="0" conaffinity="0" rgba="{colour}"/>
        <site name="thrust_{index}" pos="0 0 0" size="0.005"/>
      </body>
"""


def actuators(count):
    thrust = []
    spin = []
    for index in range(count):
        sign = -1 if index % 2 == 0 else 1
        thrust.append(f"""    <general name="thrust_{index}" site="thrust_{index}"
             gear="0 0 1 0 0 {sign * REACTION:.3f}" ctrlrange="0 {MAX_THRUST_N:g}" ctrllimited="true"/>
""")
        low, high = (-MAX_SPIN, 0) if sign < 0 else (0, MAX_SPIN)
        spin.append(f"""    <velocity name="spin_{index}" joint="rotor_{index}_joint" kv="0.0001"
              ctrlrange="{low} {high}" ctrllimited="true"/>
""")
    return "".join(thrust) + "\n" + "".join(spin)


def generate(name, count):
    rotors = "\n".join(rotor_block(i, count) for i in range(count))
    return f"""<!--
  Generated by tools/gen_multirotor.py: {name}, {count} rotors evenly spaced from +X,
  alternating spin, same take-off mass and arm length as quad_x.
-->
<mujoco model="{name}">

  <compiler angle="radian" meshdir="../../meshes"/>

  <asset>
    <mesh name="body" file="hummingbird.obj" scale="1 1 1"/>
    <mesh name="prop_cw"  file="propeller_cw.obj"  scale="0.1 0.1 0.1"/>
    <mesh name="prop_ccw" file="propeller_ccw.obj" scale="0.1 0.1 0.1"/>
  </asset>

  <worldbody>
    <body name="base_link" pos="0 0 1.0">
      <freejoint name="root"/>

      <site name="imu_site" pos="0 0 0" size="0.005"/>
      <site name="lidar_site" pos="0 0 -0.02" size="0.005" rgba="0 1 0 0.3"/>
      <site name="infrared_site" pos="0 0 -0.06" euler="180 0 0"
            size="0.003" rgba="1 0 0 0.3"/>
      <camera name="drone_camera" pos="0.085 0.085 -0.02"
              xyaxes="0 -1 0 0 0 1" fovy="60"/>

      <inertial pos="0 0 0" mass="{BODY_MASS}"
                diaginertia="0.007 0.007 0.012"/>

      <geom name="body_visual" type="mesh" mesh="body"
            contype="0" conaffinity="0" rgba="0.3 0.3 0.3 1"/>
      <geom name="body_collision" type="box" size="0.05 0.05 0.06"
            rgba="0.3 0.3 0.3 0" mass="0"/>
      <geom name="foot_0" type="sphere" size="0.012" pos="0.09 0.09 -0.07"
            rgba="0.3 0.3 0.3 0" mass="0"/>
      <geom name="foot_1" type="sphere" size="0.012" pos="-0.09 0.09 -0.07"
            rgba="0.3 0.3 0.3 0" mass="0"/>
      <geom name="foot_2" type="sphere" size="0.012" pos="-0.09 -0.09 -0.07"
            rgba="0.3 0.3 0.3 0" mass="0"/>
      <geom name="foot_3" type="sphere" size="0.012" pos="0.09 -0.09 -0.07"
            rgba="0.3 0.3 0.3 0" mass="0"/>

{rotors}    </body>
  </worldbody>

  <actuator>
{actuators(count)}  </actuator>

  <sensor>
    <accelerometer name="imu_accel" site="imu_site"/>
    <gyro          name="imu_gyro"  site="imu_site"/>
    <framequat     name="orientation" objtype="site" objname="imu_site"/>
    <framepos      name="position"   objtype="site" objname="imu_site"/>
    <framexaxis    name="heading"    objtype="site" objname="imu_site"/>
    <velocimeter   name="linvel"     site="imu_site"/>
    <frameyaxis    name="mag_y"      objtype="site" objname="imu_site"/>
    <framezaxis    name="mag_z"      objtype="site" objname="imu_site"/>
  </sensor>

</mujoco>
"""


def main():
    out_dir = sys.argv[1]
    for name, count in (("hexa", 6), ("octo", 8)):
        with open(f"{out_dir}/{name}.xml", "w") as handle:
            handle.write(generate(name, count))


main()
