import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SIZES = {
    "uint64_t": 8, "int64_t": 8, "double": 8,
    "uint32_t": 4, "int32_t": 4, "float": 4,
    "uint16_t": 2, "int16_t": 2,
    "uint8_t": 1, "int8_t": 1, "char": 1, "uint8_t_mavlink_version": 1,
}


def crc_accumulate(crc, byte):
    tmp = byte ^ (crc & 0xFF)
    tmp = (tmp ^ (tmp << 4)) & 0xFF
    return ((crc >> 8) ^ (tmp << 8) ^ (tmp << 3) ^ (tmp >> 4)) & 0xFFFF


def crc_of(text):
    crc = 0xFFFF
    for byte in text.encode("latin-1"):
        crc = crc_accumulate(crc, byte)
    return crc


def load(path, seen, messages):
    path = Path(path).resolve()
    if path in seen:
        return
    seen.add(path)
    root = ET.parse(path).getroot()
    for include in root.findall("include"):
        load(path.parent / include.text.strip(), seen, messages)
    for message in root.iter("message"):
        messages[int(message.get("id"))] = message


def parse_field(field):
    kind = field.get("type")
    count = 1
    base = kind
    if "[" in kind:
        base = kind[: kind.index("[")]
        count = int(kind[kind.index("[") + 1 : kind.index("]")])
    return {"name": field.get("name"), "type": kind, "base": base, "count": count, "size": SIZES[base]}


def layout(message):
    fields = []
    extensions = []
    in_extension = False
    for child in message:
        if child.tag == "extensions":
            in_extension = True
        elif child.tag == "field":
            (extensions if in_extension else fields).append(parse_field(child))
    wire = sorted(fields, key=lambda item: -item["size"])
    offset = 0
    positions = {}
    for item in wire + extensions:
        positions[item["name"]] = offset
        offset += item["size"] * item["count"]
    base_len = sum(item["size"] * item["count"] for item in wire)
    return wire, extensions, positions, base_len, offset


def crc_extra(name, wire):
    text = name + " "
    for item in wire:
        base = "uint8_t" if item["base"] == "uint8_t_mavlink_version" else item["base"]
        text += base + " " + item["name"] + " "
        if item["count"] > 1:
            text += chr(item["count"])
    crc = crc_of(text)
    return (crc & 0xFF) ^ (crc >> 8)


def main():
    messages = {}
    load(sys.argv[1], set(), messages)
    rows = []
    for msgid in sorted(messages):
        message = messages[msgid]
        wire, extensions, positions, base_len, max_len = layout(message)
        name = message.get("name")
        target_system = positions.get("target_system", positions.get("target", 255))
        target_component = positions.get("target_component", 255)
        rows.append((msgid, name, crc_extra(name, wire), base_len, max_len, target_system, target_component))
    expected = {0: 50, 107: 108, 113: 124, 93: 47, 69: 243, 76: 152}
    for msgid, value in expected.items():
        found = [row for row in rows if row[0] == msgid]
        if found and found[0][2] != value:
            sys.exit("generator disagrees with a known CRC extra for message %d: %d != %d" % (msgid, found[0][2], value))
    out = ["/* Generated by tools/gen_mavlink_dialect.py from the MAVLink message definitions (MIT licence). */",
           '#include "bridge/mav_dialect.h"', "",
           "const mav_message_info_t MAV_DIALECT[] = {"]
    for msgid, name, extra, base_len, max_len, target_system, target_component in rows:
        out.append("    {%d, %d, %d, %d, %d, %d}, /* %s */" % (msgid, extra, base_len, max_len, target_system, target_component, name))
    out.append("};")
    out.append("")
    out.append("const unsigned MAV_DIALECT_COUNT = sizeof(MAV_DIALECT) / sizeof(MAV_DIALECT[0]);")
    print("\n".join(out))


main()
